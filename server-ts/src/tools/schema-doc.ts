/**
 * Generate db/README.md (table plan + relationships) from the live database.
 *
 * Purposes are written by hand in schema-doc-text.ts; columns, types, keys, foreign keys and row counts are read
 * from the database, so the document always matches the schema actually loaded.
 *
 *   npm run schema-doc
 */
import fs from "node:fs";
import path from "node:path";
import { Db } from "../core/db.js";
import { loadEnv, ROOT } from "../core/env.js";
import { exit } from "./fmt.js";
import { ER, GROUPS, RESEARCH_MAP } from "./schema-doc-text.js";

async function main(): Promise<number> {
  loadEnv();
  const db = new Db();
  let cols: any[], pks: [string, string][], fks: [string, string, string, string][], counts: Record<string, number>;
  try {
    cols = await db.q(`SELECT coalesce(json_agg(x ORDER BY table_name, ordinal_position), '[]') FROM (
        SELECT c.table_name, c.column_name, c.ordinal_position, c.is_nullable,
               CASE WHEN c.data_type = 'USER-DEFINED' THEN c.udt_name WHEN c.data_type = 'ARRAY' THEN replace(c.udt_name, '_', '') || '[]'
                    ELSE c.data_type END AS type
        FROM information_schema.columns c JOIN information_schema.tables t USING (table_schema, table_name)
        WHERE c.table_schema = 'regs' AND t.table_type = 'BASE TABLE') x`);
    pks = await db.q(`SELECT coalesce(json_agg(json_build_array(tc.table_name, kcu.column_name)), '[]')
        FROM information_schema.table_constraints tc JOIN information_schema.key_column_usage kcu
          ON tc.constraint_name = kcu.constraint_name AND tc.table_schema = kcu.table_schema
        WHERE tc.table_schema = 'regs' AND tc.constraint_type = 'PRIMARY KEY'`);
    fks = await db.q(`SELECT coalesce(json_agg(json_build_array(tc.table_name, kcu.column_name, ccu.table_name, ccu.column_name)), '[]')
        FROM information_schema.table_constraints tc
        JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name AND tc.table_schema = kcu.table_schema
        JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name = tc.constraint_name AND ccu.table_schema = tc.table_schema
        WHERE tc.table_schema = 'regs' AND tc.constraint_type = 'FOREIGN KEY'`);
    counts = Object.fromEntries(await db.q(`SELECT coalesce(json_agg(json_build_array(relname, n)), '[]') FROM (
        SELECT c.relname, (xpath('/row/n/text()', query_to_xml(format('SELECT count(*) AS n FROM regs.%I', c.relname), false, true, '')))[1]::text::int AS n
        FROM pg_class c JOIN pg_namespace ns ON ns.oid = c.relnamespace WHERE ns.nspname = 'regs' AND c.relkind = 'r') x`));
  } finally {
    await db.close();
  }
  const pk = new Set(pks.map(([t, c]) => `${t}|${c}`));
  const fk = new Map(fks.map(([t, c, rt, rc]) => [`${t}|${c}`, `${rt}.${rc}`]));
  const byTable = new Map<string, any[]>();
  for (const c of cols) {
    if (!byTable.has(c.table_name)) byTable.set(c.table_name, []);
    byTable.get(c.table_name)!.push(c);
  }
  const documented = new Set(GROUPS.flatMap(([, ts]) => ts.map(([t]) => t)));
  const missing = [...byTable.keys()].filter((t) => !documented.has(t)).sort();
  if (missing.length) {
    console.error(`tables without a purpose in schema-doc-text.ts: ${JSON.stringify(missing)}`);
    return 1;
  }

  const out: string[] = [
    "# Database plan — tables and relationships",
    "",
    "> Generated by `npm run schema-doc` (server-ts/src/tools/schema-doc.ts) from the live database (schema `regs`). Do not edit by hand: re-run it after any schema change.",
    "",
    "## Where the data is",
    "",
    "* Database **`siteora`**, schema **`regs`** (26 tables, 7 views). The `public` schema is intentionally empty.",
    "* In pgAdmin / DBeaver: `siteora → Schemas → regs → Tables`. `search_path` is set to `regs, public`, so plain `SELECT * FROM zones` works after reconnecting.",
    "* Load or reload everything: `psql -h localhost -U postgres -d siteora -c \"DROP SCHEMA IF EXISTS regs CASCADE\"` then `psql -h localhost -U postgres -d siteora -v ON_ERROR_STOP=1 -f db/load_all.sql`.",
    "* Verify: `npm run verify-load` (research files → tables, record by record) and `npm run check` (integrity + worked examples).",
    "",
    "## Relationships",
    "",
    ER,
    "",
    "Every arrow is a foreign key in the database, so a row cannot point at something that does not exist.",
    "",
    "## How the research files map to tables",
    "",
    RESEARCH_MAP,
    "",
    "## Tables",
    "",
  ];
  for (const [group, tables] of GROUPS) {
    out.push(`### ${group}`, "");
    for (const [t, purpose, source] of tables) {
      out.push(`#### \`${t}\` — ${(counts[t] ?? 0).toLocaleString("en-US")} rows`, "", purpose, "", `*Loaded by:* ${source}`, "",
        "| Column | Type | Null | Key / references |", "|---|---|---|---|");
      for (const c of byTable.get(t) ?? []) {
        const key: string[] = [];
        if (pk.has(`${t}|${c.column_name}`)) key.push("**PK**");
        if (fk.has(`${t}|${c.column_name}`)) key.push(`→ \`${fk.get(`${t}|${c.column_name}`)}\``);
        out.push(`| \`${c.column_name}\` | ${c.type} | ${c.is_nullable === "YES" ? "yes" : "no"} | ${key.join(" ")} |`);
      }
      out.push("");
    }
  }
  out.push("## Views", "",
    "| View | Shows |", "|---|---|",
    "| `v_rule_catalogue` | One readable row per rule version: topic, value, unit, primary clause, document, version, status |",
    "| `v_active_rules` | Only the rules the engine uses (status ACTIVE) |",
    "| `v_setback_rules`, `v_height_rules`, `v_site_coverage_rules`, `v_pool_rules` | Typed lists filtered from the catalogue |",
    "| `v_rule_exceptions` | Every exemption / relaxation and the rule it affects |",
    "| `v_untraceable_rules` | Rules with no PRIMARY source — must always be empty |", "");
  fs.writeFileSync(path.join(ROOT, "db", "README.md"), out.join("\n"), "utf-8");
  console.log(`db/README.md written: ${byTable.size} tables, ${fks.length} foreign keys`);
  return 0;
}

main().then(exit, (e) => { console.error(e); exit(1); });
